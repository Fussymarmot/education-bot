"""Выбор эмодзи-реакции для сообщения: по ключевым словам или случайно.

Telegram разрешает ботам ставить только эмодзи из фиксированного списка
(см. ReactionTypeEmoji), поэтому все эмодзи ниже взяты строго оттуда.
"""
from __future__ import annotations

import random
import re
from dataclasses import dataclass

# --- Правила «слово → реакции» ------------------------------------------------
# Редактируйте этот список под себя. Шаблон ищется без учёта регистра и должен
# начинаться с границы слова, поэтому «зачёт» сработает на «зачётка», «зачеты» и т.д.
# Если подошло несколько правил, берётся первое (сверху вниз), а из его эмодзи -
# случайное. Бот может поставить только ОДНУ реакцию на сообщение.


@dataclass(frozen=True)
class Rule:
    pattern: re.Pattern[str]
    emojis: tuple[str, ...]


def _rule(words: str, *emojis: str) -> Rule:
    """words - регулярное выражение из альтернатив, например 'привет|здравств'."""
    return Rule(re.compile(rf"(?<!\w)(?:{words})", re.IGNORECASE), emojis)


# «Меня/нас/его не будет», «не приду», «не пойду», «не смогу прийти», «опоздаю», «прогуляю»...
# Окончания перечислены явно, чтобы не ловить «не придумал», «не является», «не пришло в голову».
_E_YO = r"(?:у|[её]м|[её]т|[её]шь|[её]те|ут)\b"   # приду, придём, придёт, придёшь, придёте, придут
_E_E = r"(?:у|ем|ет|ешь|ете|ут)\b"                # приеду, приедем, приедет, ...
_GO = r"(?:прийти|придти|быть|приехать|подъехать|присутствовать|пойти|явиться|добраться)"
ABSENCE = (
    rf"не\s+прид{_E_YO}|не\s+пойд{_E_YO}|не\s+дойд{_E_YO}|"
    rf"не\s+приед{_E_E}|не\s+поед{_E_E}|не\s+доед{_E_E}|"
    r"не\s+приш(?:[её]л|ла|ли)\b|"
    r"не\s+явл(?:юсь|имся|ится|ятся)|не\s+яв(?:ишься|итесь)|"
    r"не\s+буд(?:у|ем|ет|ут|ешь|ете)\b|"
    rf"не\s+(?:смо|мо)(?:гу|жем|жет|жешь|жете|гут)\s+(?:\w+\s+)?{_GO}|"
    rf"не\s+получится\s+(?:\w+\s+)?{_GO}|"
    r"не\s+успе(?:ю|ем|ет|ешь|ете|ют)\s+(?:на|к)\b|"
    r"отсутству(?:ю|ешь|ет|ем|ете|ют)|"
    r"опозда(?:ю|ем|ет|ешь|ете|ют)|"
    r"пропущу|пропуст(?:им|ишь|ите|ит|ят)|"
    r"прогуля(?:ю|ем|ет|ешь|ете|ют)"
)

# Отмена занятий: «завтра первой пары не будет», «не будет пары», «лекции не будет», «препода не будет».
# Существительные только в им./род. падеже («пара», «пары», «занятий»), без «на паре» / «на лекции» -
# «меня не будет на паре» - это про человека, а не про отмену.
_CLASS = (
    r"(?:пар[аы]?|пар[ао]й|занят\w*|лекци[яи]|семинар\w*|практик\w*|лабораторн\w*|лаб[аы]?|"
    r"физр\w*|физкультур\w*|урок\w*|консультаци\w*|препод\w*|преподавател\w*|учител\w*|лектор\w*)\b"
)
_NOT_ME = r"(?!меня\b|нас\b|его\b|её\b|ее\b|их\b|тебя\b|вас\b)"
_GAP = rf"(?:{_NOT_ME}\w+\s+){{0,3}}"
CANCELLED = (
    rf"(?<!на )(?<!в )(?<!во )(?<!к )(?<!с )(?<!у ){_CLASS}\s+{_GAP}не\s+буд(?:ет|ут)\b|"
    rf"не\s+буд(?:ет|ут)\s+(?!на\s|в\s|во\s){_GAP}{_CLASS}"
)

RULES: tuple[Rule, ...] = (
    _rule(CANCELLED, "🎉", "😍"),
    # Первым, чтобы «не приду на зачёт» не перехватывалось правилами ниже
    _rule(ABSENCE, "🤬", "💩", "🤮", "😡", "🖕"),
    _rule(r"спасиб|благодар", "🙏", "🥰", "🤝", "💋"),
    _rule(
        r"приве+т|првиет|прив\b|здрасть|здрасьте|здравств|здаров|даров|здорова\b|"
        r"добр(?:ое|ый|ого|ой) (?:утро|день|вечер|ночи|времени)|"
        r"хай\b|хей|хэй|хелло|хеллоу|hello|hey|hi\b|салам|салют|ку\b",
        "🤗", "🫡", "🤝",
    ),
    _rule(r"зач[её]т|экзамен|сесси|контрольн|курсов|диплом", "😱", "😨"),
    _rule(r"пересдач|двойк|неуд|не сдал|завалил", "😭"),
    _rule(r"пятёрк|пятерк|отлично|сдал[аи]?\b|ура\b|поздравл", "🎉", "🏆", "🔥", "🍾", "👏"),
    _rule(r"домашк|домашн|\bдз\b|конспект|реферат", "✍"),
    _rule(r"замен|расписани|отмен", "👀"),
    _rule(r"каникул|выходн|праздник|па(?:ры|р) не будет", "🎉", "😍"),
    _rule(r"скучн|устал|спать|сон|вставать", "🥱", "😴"),
    _rule(r"хаха|ахах|лол|ржу|смешн|кек", "🤣", "😁"),
    _rule(r"люблю|обожаю", "❤", "😍", "💋"),
    _rule(r"бот", "💅", "🫡"),
    _rule(r"клубник", "🍓"),
    _rule(r"банан", "🍌"),
    _rule(r"не люблю|ненавижу|презираю", "💔"),
)

# --- Случайные реакции на остальные сообщения ---------------------------------
# Только дружелюбные эмодзи, без грубых (🖕 🤬 💩 🤮 😡) - это учебный чат.
RANDOM_EMOJIS: tuple[str, ...] = (
    "👍", "❤", "🔥", "🥰", "👏", "😁", "🤔", "🤯", "🎉", "🤩", "🙏", "👌",
    "😍", "🐳", "💯", "🤣", "⚡", "🏆", "😎", "👀", "🤓", "🗿", "🆒", "🦄",
    "😇", "🤝", "🫡", "🤗", "😘", "👻", "🍓", "🌚", "🙈", "🤪", "🎃", "💋",
)


def match_keyword(text: str, rng: random.Random | None = None) -> str | None:
    """Эмодзи по первому подошедшему правилу или None."""
    rng = rng or random
    for rule in RULES:
        if rule.pattern.search(text):
            return rng.choice(rule.emojis)
    return None


def pick_reaction(text: str | None, chance: float, rng: random.Random | None = None) -> str | None:
    """Вернуть эмодзи для реакции или None, если реагировать не нужно.

    1. Если в тексте есть ключевое слово - реакция по правилу (всегда).
    2. Иначе - случайное эмодзи с вероятностью ``chance`` (0..1).
    """
    rng = rng or random
    if text:
        emoji = match_keyword(text, rng)
        if emoji is not None:
            return emoji
    if chance > 0 and rng.random() < chance:
        return rng.choice(RANDOM_EMOJIS)
    return None
